
CREATE TABLE public.departamentos (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  nome text NOT NULL UNIQUE,
  cor text NOT NULL DEFAULT 'clay',
  created_at timestamptz NOT NULL DEFAULT now()
);
GRANT SELECT, INSERT, UPDATE, DELETE ON public.departamentos TO authenticated;
GRANT ALL ON public.departamentos TO service_role;
ALTER TABLE public.departamentos ENABLE ROW LEVEL SECURITY;
CREATE POLICY "auth manage departamentos" ON public.departamentos FOR ALL TO authenticated USING (true) WITH CHECK (true);

CREATE TABLE public.funcoes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  departamento_id uuid NOT NULL REFERENCES public.departamentos(id) ON DELETE CASCADE,
  nome text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (departamento_id, nome)
);
GRANT SELECT, INSERT, UPDATE, DELETE ON public.funcoes TO authenticated;
GRANT ALL ON public.funcoes TO service_role;
ALTER TABLE public.funcoes ENABLE ROW LEVEL SECURITY;
CREATE POLICY "auth manage funcoes" ON public.funcoes FOR ALL TO authenticated USING (true) WITH CHECK (true);

CREATE TABLE public.pessoas (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  nome text NOT NULL,
  email text NOT NULL,
  telefone text,
  ativo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
GRANT SELECT, INSERT, UPDATE, DELETE ON public.pessoas TO authenticated;
GRANT ALL ON public.pessoas TO service_role;
ALTER TABLE public.pessoas ENABLE ROW LEVEL SECURITY;
CREATE POLICY "auth manage pessoas" ON public.pessoas FOR ALL TO authenticated USING (true) WITH CHECK (true);

CREATE TABLE public.pessoa_departamentos (
  pessoa_id uuid NOT NULL REFERENCES public.pessoas(id) ON DELETE CASCADE,
  departamento_id uuid NOT NULL REFERENCES public.departamentos(id) ON DELETE CASCADE,
  PRIMARY KEY (pessoa_id, departamento_id)
);
GRANT SELECT, INSERT, UPDATE, DELETE ON public.pessoa_departamentos TO authenticated;
GRANT ALL ON public.pessoa_departamentos TO service_role;
ALTER TABLE public.pessoa_departamentos ENABLE ROW LEVEL SECURITY;
CREATE POLICY "auth manage pessoa_departamentos" ON public.pessoa_departamentos FOR ALL TO authenticated USING (true) WITH CHECK (true);

CREATE TABLE public.pessoa_funcoes (
  pessoa_id uuid NOT NULL REFERENCES public.pessoas(id) ON DELETE CASCADE,
  funcao_id uuid NOT NULL REFERENCES public.funcoes(id) ON DELETE CASCADE,
  PRIMARY KEY (pessoa_id, funcao_id)
);
GRANT SELECT, INSERT, UPDATE, DELETE ON public.pessoa_funcoes TO authenticated;
GRANT ALL ON public.pessoa_funcoes TO service_role;
ALTER TABLE public.pessoa_funcoes ENABLE ROW LEVEL SECURITY;
CREATE POLICY "auth manage pessoa_funcoes" ON public.pessoa_funcoes FOR ALL TO authenticated USING (true) WITH CHECK (true);

CREATE TABLE public.cultos (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  titulo text NOT NULL,
  data date NOT NULL,
  horario time NOT NULL DEFAULT '19:00',
  created_at timestamptz NOT NULL DEFAULT now()
);
GRANT SELECT, INSERT, UPDATE, DELETE ON public.cultos TO authenticated;
GRANT ALL ON public.cultos TO service_role;
ALTER TABLE public.cultos ENABLE ROW LEVEL SECURITY;
CREATE POLICY "auth manage cultos" ON public.cultos FOR ALL TO authenticated USING (true) WITH CHECK (true);

CREATE TABLE public.escalas (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  culto_id uuid NOT NULL REFERENCES public.cultos(id) ON DELETE CASCADE,
  funcao_id uuid NOT NULL REFERENCES public.funcoes(id) ON DELETE CASCADE,
  pessoa_id uuid NOT NULL REFERENCES public.pessoas(id) ON DELETE CASCADE,
  aviso_enviado_em timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (culto_id, funcao_id, pessoa_id)
);
GRANT SELECT, INSERT, UPDATE, DELETE ON public.escalas TO authenticated;
GRANT ALL ON public.escalas TO service_role;
ALTER TABLE public.escalas ENABLE ROW LEVEL SECURITY;
CREATE POLICY "auth manage escalas" ON public.escalas FOR ALL TO authenticated USING (true) WITH CHECK (true);

